var update = flag.Bool("update", false, "rewrite testdata/vectors.json")

const vectorsPath = "../testdata/vectors.json"

// Vectors is the shared test-vector file (SPEC.md).
type Vectors struct {
	Note       string    `json:"note"`
	PrivateKey string    `json:"private_key"`
	PublicKey  string    `json:"public_key"`
	Claims     []Vector  `json:"claims"`
	Invalid    []Invalid `json:"invalid"`
	Tree       Tree      `json:"tree"`
}

// Vector is one valid claim.
type Vector struct {
	FileHex  string `json:"file_hex"`
	SHA256   string `json:"sha256"`
	Type     string `json:"type"`
	Captured int64  `json:"captured"`
	Claim    string `json:"claim"`
	Signed   string `json:"signed"`
	ID       string `json:"id"`
}

// Invalid is a signed claim every implementation must reject.
type Invalid struct {
	Why    string `json:"why"`
	Signed string `json:"signed"`
}

// Tree is the tree over the valid claims' ids, in order.
type Tree struct {
	Root   string     `json:"root"`
	Proofs [][]string `json:"proofs"`
}

func testKey() *ecdsa.PrivateKey {
	d := sha256.Sum256([]byte("stillproof test key, never use"))
	k, err := ecdsa.ParseRawPrivateKey(elliptic.P256(), d[:])
	if err != nil {
		panic(err)
	}
	return k
}

func generate(t *testing.T) Vectors {
	key := testKey()
	raw, _ := key.Bytes()
	pub, _ := key.PublicKey.Bytes()
	v := Vectors{
		Note:       "Generated by `go test ./claim -update`. Signatures are randomised, so regenerate only on purpose.",
		PrivateKey: hex.EncodeToString(raw),
		PublicKey:  hex.EncodeToString(pub),
	}
	files := []struct {
		data, typ string
		at        int64
	}{
		{"", "image/jpeg", 0},
		{"stillproof", "image/png", 1762300800000},
		{strings.Repeat("\xff\xd8\xff\xe0", 64), "image/jpeg", 1762344000123},
	}
	var leaves []merkle.Hash
	for _, f := range files {
		c := Claim{SHA256: sha256.Sum256([]byte(f.data)), Type: f.typ, Captured: f.at, Key: &key.PublicKey}
		s, err := Sign(c, key)
		if err != nil {
			t.Fatal(err)
		}
		leaves = append(leaves, LeafHash(s.Bytes()))
		v.Claims = append(v.Claims, Vector{
			FileHex: hex.EncodeToString([]byte(f.data)), SHA256: hex.EncodeToString(c.SHA256[:]),
			Type: f.typ, Captured: f.at, Claim: string(c.Bytes()), Signed: string(s.Bytes()), ID: s.ID(),
		})
	}
	root := merkle.Root(leaves)
	v.Tree.Root = hex.EncodeToString(root[:])
	for i := range leaves {
		var p []string
		for _, h := range merkle.Proof(leaves, i) {
			p = append(p, hex.EncodeToString(h[:]))
		}
		v.Tree.Proofs = append(v.Tree.Proofs, p)
	}

	good := v.Claims[1].Signed
	sigAt := strings.LastIndex(good, "sig ") + 4
	sig, _ := hex.DecodeString(good[sigAt : sigAt+128])
	n := elliptic.P256().Params().N
	highS := new(big.Int).Sub(n, new(big.Int).SetBytes(sig[32:]))
	high := hex.EncodeToString(sig[:32]) + hex.EncodeToString(highS.FillBytes(make([]byte, 32)))
	v.Invalid = []Invalid{
		{"high s", good[:sigAt] + high + "\n"},
		{"uppercase hex", strings.Replace(good, "sha256 "+v.Claims[1].SHA256, "sha256 "+strings.ToUpper(v.Claims[1].SHA256), 1)},
		{"missing final newline", strings.TrimSuffix(good, "\n")},
		{"carriage returns", strings.ReplaceAll(good, "\n", "\r\n")},
		{"wrong header", strings.Replace(good, "stillproof/claim/v0", "stillproof/claim/v1", 1)},
		{"leading zero in captured", strings.Replace(good, "captured 1762300800000", "captured 01762300800000", 1)},
		{"file hash changed after signing", strings.Replace(good, v.Claims[1].SHA256, v.Claims[0].SHA256, 1)},
	}
	return v
}

func load(t *testing.T) Vectors {
	t.Helper()
	if *update {
		b, _ := json.MarshalIndent(generate(t), "", "  ")
		if err := os.WriteFile(vectorsPath, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	var v Vectors
	if err := json.Unmarshal(b, &v); err != nil {
		t.Fatal(err)
	}
	return v
}

func TestVectors(t *testing.T) {
	v := load(t)
	pub, _ := testKey().PublicKey.Bytes()
	if v.PublicKey != hex.EncodeToString(pub) {
		t.Fatal("public key does not match the test key")
	}
	var leaves []merkle.Hash
	for i, c := range v.Claims {
		s, err := Parse([]byte(c.Signed))
		if err != nil {
			t.Fatalf("claim %d: %v", i, err)
		}
		if err := s.Verify(); err != nil {
			t.Fatalf("claim %d: %v", i, err)
		}
		file, _ := hex.DecodeString(c.FileHex)
		if sha256.Sum256(file) != s.SHA256 || string(s.Claim.Bytes()) != c.Claim || s.ID() != c.ID {
			t.Fatalf("claim %d: does not match its vector", i)
		}
		leaves = append(leaves, LeafHash([]byte(c.Signed)))
	}
	root := merkle.Root(leaves)
	if hex.EncodeToString(root[:]) != v.Tree.Root {
		t.Fatal("tree root does not match")
	}
	for i, p := range v.Tree.Proofs {
		var path []merkle.Hash
		for _, h := range p {
			var x merkle.Hash
			b, _ := hex.DecodeString(h)
			copy(x[:], b)
			path = append(path, x)
		}
		if err := merkle.Verify(leaves[i], i, len(leaves), path, root); err != nil {
			t.Fatalf("proof %d: %v", i, err)
		}
	}
	for _, bad := range v.Invalid {
		s, err := Parse([]byte(bad.Signed))
		if err == nil {
			err = s.Verify()
		}
		if !errors.Is(err, ErrFormat) && !errors.Is(err, ErrSignature) {
			t.Errorf("%s: accepted", bad.Why)
		}
	}
}

func TestSignAlwaysGivesLowS(t *testing.T) {
	key := testKey()
	c := Claim{Type: "image/jpeg", Captured: 1, Key: &key.PublicKey}
	half := new(big.Int).Rsh(elliptic.P256().Params().N, 1)
	for range 64 {
		s, err := Sign(c, key)
		if err != nil {
			t.Fatal(err)
		}
		if new(big.Int).SetBytes(s.Sig[32:]).Cmp(half) > 0 {
			t.Fatal("high s")
		}
		if err := s.Verify(); err != nil {
			t.Fatal(err)
		}
	}
}

func TestBadClaimsAreNotSigned(t *testing.T) {
	key := testKey()
	for _, c := range []Claim{
		{Type: "Image/JPEG", Key: &key.PublicKey},
		{Type: "jpeg", Key: &key.PublicKey},
		{Type: "image/jpeg", Captured: -1, Key: &key.PublicKey},
		{Type: "image/jpeg"},
	} {
		if _, err := Sign(c, key); !errors.Is(err, ErrFormat) {
			t.Errorf("%+v: signed", c)
		}
	}
}
